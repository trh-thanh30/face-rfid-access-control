import console from "node:console";
import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";
import {
  ACCESS_CONTRACT_VERSION,
  ACCESS_CONTRACT_VERSION_HEADER,
  ACCESS_REASON_CODES,
  ACTUATION_STATUSES,
  AUTH_SESSION_STATUSES,
  DEVICE_ENDPOINTS,
  DEVICE_CODE_HEADER,
} from "../dist/index.js";

const outputUrl = new URL(
  "../../../firmware/esp32-access-device/include/generated/access_contracts.h",
  import.meta.url,
);
const outputPath = fileURLToPath(outputUrl);

function renderStringArray(name, values) {
  const entries = values.map((value) => `    "${value}",`).join("\n");
  return `static constexpr const char* ${name}[] = {\n${entries}\n};`;
}

function renderHeader() {
  return `// Generated by @access/shared. Do not edit manually.
#pragma once

namespace access_contract {
static constexpr char kVersion[] = "${ACCESS_CONTRACT_VERSION}";
static constexpr char kVersionHeader[] = "${ACCESS_CONTRACT_VERSION_HEADER}";
static constexpr char kDeviceCodeHeader[] = "${DEVICE_CODE_HEADER}";

static constexpr char kHeartbeatPath[] = "${DEVICE_ENDPOINTS.heartbeat}";
static constexpr char kAccessSessionsPath[] = "${DEVICE_ENDPOINTS.accessSessions}";
static constexpr char kAccessSessionByIdPath[] = "${DEVICE_ENDPOINTS.accessSessionById}";
static constexpr char kAcknowledgeCommandPath[] = "${DEVICE_ENDPOINTS.acknowledgeCommand}";

${renderStringArray("kAuthSessionStatuses", AUTH_SESSION_STATUSES)}

${renderStringArray("kAccessReasonCodes", ACCESS_REASON_CODES)}

${renderStringArray("kActuationStatuses", ACTUATION_STATUSES)}
}  // namespace access_contract
`;
}

const expected = renderHeader();

if (process.argv.includes("--check")) {
  let actual;
  try {
    actual = await readFile(outputUrl, "utf8");
  } catch {
    throw new Error(`Missing generated firmware contract: ${outputPath}`);
  }

  if (actual !== expected) {
    throw new Error(
      `Firmware contract is stale. Run: pnpm contracts:generate (${outputPath})`,
    );
  }

  console.log(`Firmware contract is current: ${outputPath}`);
} else {
  await writeFile(outputUrl, expected, "utf8");
  console.log(`Generated firmware contract: ${outputPath}`);
}
